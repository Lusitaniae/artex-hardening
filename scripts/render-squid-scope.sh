#!/usr/bin/env bash
# Regenerate the IP-literal scope ACL in proxy/squid.conf from nftables/scope.allow.
#
# Why this exists: dstdomain cannot match a request to a bare IP, so an agent that
# pivots from https://api.client.example/ to http://203.0.113.10/ is denied by name
# even though the kernel permits it. That is a silent capability gap, not a scope
# decision -- it shows up as TCP_DENIED/403 on a numeric host.
#
# Keeping the two lists generated from one file is the point: a squid ACL that
# drifts from nftables is the application-level-vs-kernel mismatch this repo
# keeps finding (cf. the 172.28/172.18 gateway bug).
#
# Usage:
#   ./scripts/render-squid-scope.sh                      # rewrite the block in place
#   ./scripts/render-squid-scope.sh --check              # exit 1 if the block is stale
#   ./scripts/render-squid-scope.sh --profile acme-2026-11 [--check]
#
# It renders two blocks from the active profile:
#   scope_ips      <- scope.allow         (IP literals; empty scope.allow is an error)
#   scope_domains  <- scope.domains.allow (client names; missing/empty means deny)
#
# The generated block always reflects the *active* profile's allowlists. If you
# switch profiles without re-rendering, the relay and the kernel disagree -- which
# is the failure this script exists to make loud.
set -euo pipefail
cd "$(dirname "$0")/.."

CHECK=0
PROFILE=""
while [ "$#" -gt 0 ]; do
  case "$1" in
    --check) CHECK=1; shift ;;
    --profile) PROFILE="${2:-}"; shift 2 ;;
    --profile=*) PROFILE="${1#*=}"; shift ;;
    *) echo "unknown arg: $1" >&2; exit 2 ;;
  esac
done

ALLOW_DIR="nftables"
[ -n "$PROFILE" ] && ALLOW_DIR="nftables/profiles/$PROFILE"
[ -d "$ALLOW_DIR" ] || { echo "profile not found: $ALLOW_DIR" >&2; exit 1; }

SCOPE="$ALLOW_DIR/scope.allow"
CONF="proxy/squid.conf"
BEGIN="# BEGIN scope_ips (generated by scripts/render-squid-scope.sh — do not edit by hand)"
END="# END scope_ips"
DOMAINS_FILE="$ALLOW_DIR/scope.domains.allow"
DBEGIN="# BEGIN scope_domains (generated by scripts/render-squid-scope.sh — do not edit by hand)"
DEND="# END scope_domains"

[ -f "$SCOPE" ] || { echo "missing $SCOPE" >&2; exit 1; }
[ -f "$CONF" ]  || { echo "missing $CONF" >&2; exit 1; }

mapfile -t CIDRS < <(sed -E 's/#.*//' "$SCOPE" \
  | grep -vE '^[[:space:]]*$' \
  | grep -oE '([0-9]{1,3}\.){3}[0-9]{1,3}(/[0-9]{1,2})?' | sort -u)

if [ "${#CIDRS[@]}" -eq 0 ]; then
  echo "scope.allow has no CIDRs — refusing to render an empty ACL" >&2
  exit 1
fi

block="$BEGIN"
block+=$'\n# IP-literal reach for in-scope space only. Generated from '"$SCOPE"' ('"${#CIDRS[@]}"' CIDRs).'
block+=$'\n# Everything outside these prefixes is still name-gated: a bare IP on the CDN'
block+=$'\n# or anywhere else stays denied.'
for c in "${CIDRS[@]}"; do block+=$'\nacl scope_ips dst '"$c"; done
block+=$'\n'"$END"

DOMAINS=()
if [ -f "$DOMAINS_FILE" ]; then
  mapfile -t DOMAINS < <(sed -E 's/#.*//' "$DOMAINS_FILE" \
    | grep -vE '^[[:space:]]*$' \
    | grep -oE '([a-zA-Z0-9]([a-zA-Z0-9-]*[a-zA-Z0-9])?\.)+[a-zA-Z]{2,}' | sort -u)
fi

dblock="$DBEGIN"
if [ "${#DOMAINS[@]}" -eq 0 ]; then
  dblock+=$'\n# Empty: no name is in scope. Populate '"$DOMAINS_FILE"' for the active'
  dblock+=$'\n# profile to grant name-level reach. An empty ACL denies every name.'
else
  dblock+=$'\n# Name-level scope, generated from '"$DOMAINS_FILE"' ('"${#DOMAINS[@]}"' names).'
  dblock+=$'\n# nftables admits the CDN edge; this ACL narrows it to the client'"'"'s names.'
  for d in "${DOMAINS[@]}"; do dblock+=$'\nacl scope_domains dstdomain .'"$d"; done
fi
dblock+=$'\n'"$DEND"

rendered="$(awk -v block="$block" -v b="$BEGIN" -v e="$END" '
  $0==b {print block; skip=1; next}
  $0==e {skip=0; next}
  !skip {print}
' "$CONF")"

rendered="$(printf '%s\n' "$rendered" | awk -v block="$dblock" -v b="$DBEGIN" -v e="$DEND" '
  $0==b {print block; skip=1; next}
  $0==e {skip=0; next}
  !skip {print}
')"

if [ "$CHECK" -eq 1 ]; then
  if [ "$rendered" = "$(cat "$CONF")" ]; then
    echo "rendered blocks are current (${#CIDRS[@]} CIDRs, ${#DOMAINS[@]} names)"
    exit 0
  fi
  echo "STALE: $CONF does not match $ALLOW_DIR — run ./scripts/render-squid-scope.sh${PROFILE:+ --profile $PROFILE}" >&2
  exit 1
fi

printf '%s\n' "$rendered" > "$CONF"
echo "rendered ${#CIDRS[@]} scope_ips ACLs and ${#DOMAINS[@]} scope_domains ACLs into $CONF"
